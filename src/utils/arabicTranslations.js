export const arabicByEnglish = new Map(entries);

const normalize = (value) => value.replace(/\s+/g, " ").trim();

const dynamicArabic = (value) => {
  let match = value.match(/^Show (.+) use case$/);
  if (match) return `عرض حالة استخدام ${arabicByEnglish.get(match[1]) || match[1]}`;

  match = value.match(/^Show (.+)$/);
  if (match) return `عرض ${arabicByEnglish.get(match[1]) || match[1]}`;

  match = value.match(/^Speekr pricing customer logo (\d+)$/);
  if (match) return `شعار عميل Speekr رقم ${match[1]}`;

  return null;
};

export function translateUiValue(value, locale) {
  if (typeof value !== "string" || !value.trim()) return value;
  if (locale !== "ar") return value;

  const normalized = normalize(value);
  const translated = arabicByEnglish.get(normalized) || dynamicArabic(normalized);

  if (!translated) return value;

  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${trailing}`;
}
